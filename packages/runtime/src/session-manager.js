import { randomUUID } from 'node:crypto';
import { InMemorySessionStore, SessionNotFoundError, assertSessionId } from './session-store.js';

function isRecord(value) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function timestamp(clock) {
  const value = clock();
  if (typeof value !== 'string' || value.length === 0) throw new TypeError('clock must return a non-empty timestamp string.');
  return value;
}

/** Manages serial user turns over one AgentLoop and a revisioned session store. */
export class AgentSessionManager {
  #loop;
  #store;
  #idFactory;
  #clock;
  #activeSessionId;

  constructor({
    loop,
    store = new InMemorySessionStore(),
    idFactory = randomUUID,
    clock = () => new Date().toISOString(),
  } = {}) {
    if (!loop || typeof loop.run !== 'function') throw new TypeError('loop must implement run().');
    if (!store || !['create', 'get', 'save', 'delete'].every(method => typeof store[method] === 'function')) {
      throw new TypeError('store must implement create(), get(), save(), and delete().');
    }
    if (typeof idFactory !== 'function') throw new TypeError('idFactory must be a function.');
    if (typeof clock !== 'function') throw new TypeError('clock must be a function.');
    this.#loop = loop;
    this.#store = store;
    this.#idFactory = idFactory;
    this.#clock = clock;
  }

  async create({ id = this.#idFactory(), metadata = {} } = {}) {
    assertSessionId(id);
    if (!isRecord(metadata)) throw new TypeError('metadata must be an object.');
    const now = timestamp(this.#clock);
    return this.#store.create({
      id,
      status: 'active',
      revision: 0,
      createdAt: now,
      updatedAt: now,
      metadata: structuredClone(metadata),
      messages: [],
      turnCount: 0,
      modelRoundCount: 0,
      turns: [],
    });
  }

  async get(id) {
    assertSessionId(id);
    const record = await this.#store.get(id);
    if (!record) throw new SessionNotFoundError(id);
    return record;
  }

  async run(id, input, { signal } = {}) {
    assertSessionId(id);
    if (input === undefined) throw new TypeError('input must be provided.');
    const turnInput = structuredClone(input);
    if (this.#activeSessionId !== undefined) {
      throw new Error('AgentSessionManager already has an active turn for session ' + this.#activeSessionId + '.');
    }
    this.#activeSessionId = id;

    try {
      let record = await this.#store.get(id);
      if (!record) throw new SessionNotFoundError(id);
      if (record.status !== 'active') throw new Error('Cannot run a closed session: ' + id);

      // Restored sessions can contain IDs generated by a prior process.
      // A deterministic/test ID factory may restart its counter; never update
      // the wrong journal entry on completion just because IDs collide.
      let newTurnId;
      for (let attempt = 0; attempt < 32; attempt++) {
        const candidate = assertSessionId(this.#idFactory());
        if (!record.turns.some(existing => existing.id === candidate)) {
          newTurnId = candidate;
          break;
        }
      }
      if (!newTurnId) throw new Error('Unable to allocate a unique turn ID for resumed session.');

      const turn = {
        id: newTurnId,
        status: 'running',
        input: turnInput,
        startedAt: timestamp(this.#clock),
        completedAt: null,
        result: null,
        error: null,
      };
      record.turns.push(turn);
      record.updatedAt = timestamp(this.#clock);
      record = await this.#store.save(record, { expectedRevision: record.revision });

      // The original CLI appends completed transcript entries while a query
      // is still running. A successful Edit/Bash must not be lost because
      // the NEXT model request failed. Reuse Query's committed tool-result and
      // compaction checkpoints; serialize revisioned writes through the same
      // FileSessionStore already used by this manager.
      let checkpointWrites = Promise.resolve();
      const persistCheckpoint = ({ committedMessages } = {}) => {
        if (!Array.isArray(committedMessages)) return;
        const snapshot = structuredClone(committedMessages);
        checkpointWrites = checkpointWrites.then(async () => {
          const next = { ...record, messages: snapshot, updatedAt: timestamp(this.#clock) };
          record = await this.#store.save(next, { expectedRevision: record.revision });
        });
        // A disk write may fail while the model is still streaming. Mark the
        // rejection observed immediately; the enclosing run still awaits the
        // original rejected promise and reports the storage failure.
        void checkpointWrites.catch(() => {});
      };
      const listen = typeof this.#loop.on === 'function' &&
        typeof this.#loop.off === 'function';
      if (listen) {
        this.#loop.on('turnFinished', persistCheckpoint);
        this.#loop.on('contextCompacted', persistCheckpoint);
      }

      let result;
      try {
        try {
          result = await this.#loop.run({ messages: record.messages, input: turnInput, signal });
          await checkpointWrites;
        } finally {
          if (listen) {
            this.#loop.off('turnFinished', persistCheckpoint);
            this.#loop.off('contextCompacted', persistCheckpoint);
          }
        }
      } catch (error) {
        // The model may reject while the last successful checkpoint is still
        // on disk's write queue. Never persist the failed turn first.
        try {
          await checkpointWrites;
        } catch (persistError) {
          throw new AggregateError([error, persistError],
            'Agent turn ended before its completed tool results could be persisted.',
            { cause: error });
        }
        const failedTurn = record.turns.find(item => item.id === turn.id);
        failedTurn.status = signal?.aborted || error?.name === 'AbortError' ? 'cancelled' : 'failed';
        failedTurn.completedAt = timestamp(this.#clock);
        failedTurn.error = {
          name: typeof error?.name === 'string' ? error.name : 'Error',
          message: error instanceof Error ? error.message : String(error),
        };
        record.updatedAt = timestamp(this.#clock);
        try {
          await this.#store.save(record, { expectedRevision: record.revision });
        } catch (persistError) {
          throw new AggregateError(
            [error, persistError],
            'Agent turn failed and its failure status could not be persisted.',
            { cause: error },
          );
        }
        throw error;
      }

      record.messages = result.messages;
      record.turnCount += 1;
      record.modelRoundCount += result.turns;
      const completedTurn = record.turns.find(item => item.id === turn.id);
      completedTurn.status = 'completed';
      completedTurn.completedAt = timestamp(this.#clock);
      completedTurn.result = { stopReason: result.stopReason, modelRounds: result.turns };
      record.updatedAt = timestamp(this.#clock);
      const saved = await this.#store.save(record, { expectedRevision: record.revision });
      return { session: saved, result };
    } finally {
      this.#activeSessionId = undefined;
    }
  }

  async recoverInterruptedTurns(id) {
    assertSessionId(id);
    if (this.#activeSessionId === id) throw new Error('Cannot recover a session while its turn is running.');
    let record = await this.#store.get(id);
    if (!record) throw new SessionNotFoundError(id);
    const interrupted = record.turns.filter(turn => turn.status === 'running');
    if (interrupted.length === 0) return record;

    for (const turn of interrupted) {
      turn.status = 'interrupted';
      turn.completedAt = timestamp(this.#clock);
      turn.error = {
        name: 'InterruptedTurnError',
        message: 'The previous runtime ended before this turn was committed. Review side effects before retrying.',
      };
    }
    record.updatedAt = timestamp(this.#clock);
    return this.#store.save(record, { expectedRevision: record.revision });
  }

  async close(id) {
    assertSessionId(id);
    if (this.#activeSessionId === id) throw new Error('Cannot close a session while its turn is running.');
    let record = await this.#store.get(id);
    if (!record) throw new SessionNotFoundError(id);
    if (record.status === 'closed') return record;
    record.status = 'closed';
    record.updatedAt = timestamp(this.#clock);
    return this.#store.save(record, { expectedRevision: record.revision });
  }

  async delete(id) {
    assertSessionId(id);
    if (this.#activeSessionId === id) throw new Error('Cannot delete a session while its turn is running.');
    const record = await this.#store.get(id);
    if (!record) return false;
    return this.#store.delete(id, { expectedRevision: record.revision });
  }
}
